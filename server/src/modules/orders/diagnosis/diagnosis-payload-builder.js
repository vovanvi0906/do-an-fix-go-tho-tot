import { randomUUID } from 'node:crypto';
import { STATUS, DECISION_SOURCE, REASON_CODES, MODEL_VERSION } from './diagnosis-constants';

export function createInitialResult(imageUrl, description, categories) {
  return {
    requestId: randomUUID(),
    status: STATUS.MANUAL_SELECTION,
    source: DECISION_SOURCE.MANUAL,
    imageUrl,
    confidence: null,
    modelScore: null,
    detectedLabels: [],
    categoryCandidates: [],
    targetCandidates: [],
    suggestedCategoryId: null,
    suggestedCategoryName: null,
    suggestedTargetId: null,
    suggestedTargetName: null,
    suggestedServiceId: null,
    suggestedServiceName: null,
    suggestedServiceConfidence: null,
    suggestedServices: [],
    estimatedPriceMin: null,
    estimatedPriceMax: null,
    estimatedPriceRange: null,
    category: null,
    target: null,
    service: null,
    priceEstimate: null,
    requiresManualSelection: true,
    needsMoreInfo: false,
    decisionSource: DECISION_SOURCE.MANUAL,
    modelVersion: MODEL_VERSION,
    reasonCodes: [REASON_CODES.CATEGORY_REQUIRED],
    observableSigns: [],
    reportedSymptoms: [],
    questions: [],
    availableCategories: categories.map((c) => ({ id: c.id, name: c.name, basePrice: Number(c.basePrice) })),
    availableTargets: [],
    availableServices: [],
    issueDescription: description,
    reason: REASON_CODES.CATEGORY_REQUIRED,
    notes: 'Vui lòng chọn danh mục và dịch vụ phù hợp.',
    message: 'Vui lòng chọn danh mục và dịch vụ phù hợp.',
  };
}
