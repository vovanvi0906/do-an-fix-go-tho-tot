class StudioTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory(prefix='fixgo-studio-test-');self.root=Path(self.tmp.name);audit=self.root/'audit';(audit/'evidence').mkdir(parents=True)
        self.catalog={'categories':[{'id':'c','name':'Điện','slug':'sua-dien'}],'targets':[{'id':'t','slug':'o-cam-dien','name':'Ổ cắm','categoryId':'c'}]}
        (audit/'evidence/catalog.json').write_text(canonical(self.catalog));(audit/'evidence/ontology.json').write_text(canonical({'signs':{'burn_mark':{'name':'Cháy xém','evidenceRule':'Visible only'}}}))
        rows=[]
        for n in range(4):
            image=self.root/f'{n}.png';Image.new('RGB',(100,100),(n*30,20,30)).save(image)
            rows.append(dict(image_id=f'i{n}',path=str(image),sha256=digest(image.read_bytes()),width='100',height='100',format='PNG',corpus='fixture',proposed_source_component=f'g{n}',component_exposure_json='[]',direct_experiment_exposure_json='[]',annotations_json='[]',candidate_target_ids_json='["t"]',object_box_reuse_candidates_json='[]',real_or_synthetic='unknown',pixel_sha256='',phash_component_id='',sha_group_id='',pixel_group_id=''))
        self.inventory=audit/'image-inventory.csv'
        with self.inventory.open('w',newline='') as f:w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
        self.s=Studio(self.inventory,self.root/'state')
    def tearDown(self):self.s.close();self.tmp.cleanup()
    def payload(self,i='i0',verified=False):
        return dict(imageId=i,contentHash=self.s.rows[i]['sha256'],expectedRevision=(self.s.studio_latest.get(i) or {}).get('eventHash'),reviewer='Fixture Reviewer',note='Isolated test evidence only',reviewStatus='HUMAN_VERIFIED' if verified else 'NEEDS_REVIEW',outcome='NORMAL',targetIds=['t'],boxes=[dict(id='object1',kind='object',label='t',xyxy=[.1,.1,.8,.8],objectId=None)],reviewChecks={k:True for k in ['imageSeen','objectExtent','allSigns','objectAssociation']},sourceEvidence='Isolated fixture created in this test',licenseStatus='VERIFIED',licenseType='owned',licenseEvidence='Fixture generated by this test; not source image rights',licenseConfirmed=True)
    def test_explicit_verification_revision_and_history(self):
        p=self.payload(verified=True);p['reviewChecks']={}
        with self.assertRaises(ValueError):self.s.save(p)
        p=self.payload();e=self.s.save(p);self.assertEqual(self.s.status('i0'),'NEEDS_REVIEW')
        with self.assertRaises(ValueError):self.s.save(p)
        p=self.payload(verified=True);v=self.s.save(p);self.assertFalse(v['approvedGroundTruth']);self.assertEqual(self.s.status('i0'),'HUMAN_VERIFIED')
        r=self.s.restore(dict(imageId='i0',revision=e['eventHash'],expectedRevision=v['eventHash'],reviewer='Fixture Reviewer',note='Restore test'))
        self.assertEqual(r['reviewStatus'],'NEEDS_REVIEW');self.assertEqual(r['licenseStatus'],'UNVERIFIED');self.assertEqual(len(self.s.revisions['i0']),3)
    def test_multiple_signs_and_link_validation(self):
        p=self.payload(verified=True);p['outcome']='ABNORMAL';p['reviewChecks']['signTargetCompatibility']=True
        p['boxes'] += [dict(id='sign1',kind='sign',label='burn_mark',xyxy=[.2,.2,.3,.3],objectId='object1'),dict(id='sign2',kind='sign',label='burn_mark',xyxy=[.4,.4,.5,.5],objectId='object1')]
        e=self.s.save(p);self.assertEqual(len(e['boundingBoxes']),3)
        p=self.payload();p['boxes'].append(dict(id='bad',kind='sign',label='burn_mark',xyxy=[.1,.1,.2,.2],objectId='missing'))
        with self.assertRaises(ValueError):self.s.save(p)
        p['boxes'][-1]['objectId']='object1';p['boxes'][-1]['label']='motor_failure'
        with self.assertRaises(ValueError):self.s.save(p)
    def test_bulk_cannot_verify_or_copy_boxes(self):
        with self.assertRaises(ValueError):self.s.bulk(dict(imageIds=['i0'],reviewStatus='HUMAN_VERIFIED'))
        r=self.s.bulk(dict(imageIds=['i0','i1'],reviewStatus='NEEDS_REVIEW',reviewer='Fixture Reviewer',note='Bulk queue review'));self.assertEqual(r['saved'],2)
        self.assertEqual(self.s.studio_latest['i0']['boundingBoxes'],[]);self.assertEqual(self.s.studio_latest['i0']['licenseStatus'],'UNVERIFIED')
    def test_session_and_log_reload_tamper(self):
        self.s.save(self.payload());self.s.save_session({'currentImageId':'i0'});self.s.close();self.s=Studio(self.inventory,self.root/'state');self.assertEqual(self.s.session['currentImageId'],'i0');self.assertEqual(len(self.s.revisions['i0']),1)
        self.s.studio_log.write_text(self.s.studio_log.read_text().replace('Fixture Reviewer','Bad Reviewer'))
        with self.assertRaises(ValueError):self.s.save(self.payload())
    def test_bad_geometry_and_source_change(self):
        p=self.payload();p['boxes'][0]['xyxy']=[.2,.2,.201,.3]
        with self.assertRaises(ValueError):self.s.save(p)
        p=self.payload();Path(self.s.rows['i0']['path']).write_bytes(b'changed')
        with self.assertRaises(ValueError):self.s.save(p)
    def test_export_gates_and_version(self):
        before=Path(self.s.rows['i0']['path']).read_bytes()
        with self.assertRaises(ValueError):export(self.s,['i0'],'yolo','blocked')
        self.assertFalse((self.s.state/'exports/blocked').exists())
        p=self.payload(verified=True);p['licenseStatus']='UNVERIFIED';self.s.save(p)
        with self.assertRaises(ValueError):export(self.s,['i0'],'metadata','rights-blocked')
        self.s.save(self.payload(verified=True));r=export(self.s,['i0'],'yolo','fixture-v1');dest=Path(r['path']);self.assertTrue((dest/'data.yaml').exists());self.assertEqual(before,Path(self.s.rows['i0']['path']).read_bytes());self.assertFalse(json.loads((dest/'manifest.json').read_text())['independentTest'])
        with self.assertRaises(ValueError):export(self.s,['i0'],'yolo','fixture-v1')
        export(self.s,['i0'],'classification','fixture-class');export(self.s,['i0'],'metadata','fixture-meta')
    def test_duplicate_bridge_determinism_synthetic_exposure(self):
        self.s.rows['i0']['pixel_sha256']='same';self.s.rows['i1']['pixel_sha256']='same';self.s.rows['i1']['phash_component_id']='bridge';self.s.rows['i2']['phash_component_id']='bridge'
        self.s.rows['i1']['component_exposure_json']='["train"]';splits,_=partition(self.s,['i0','i2','i3'],42)
